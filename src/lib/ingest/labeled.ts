// 「部署: 営業 / 客先: A社」のような「項目名: 値」を文書の冒頭から探すための共通部品。
// 部署（department.ts）と客先・日付（metadata.ts）で同じ切り方を使う。
// 切り方が食い違うと、部署の判定が客先の欄まで読んでしまい、書かれていない部署に権限が付く。

/** 項目名の直前が漢字・英字なら別の語の一部（例: 宛先部署、主要客先）なので対象外にする */
export const BEFORE = String.raw`(?<![一-龥ァ-ヶa-zA-Z])`;

/**
 * 項目の値。改行か、項目区切りの " / "（前後に空白あり）の手前までを max 文字まで取る。
 * 日付の「2023/12/5」の / は区切りと見なさない。キャプチャグループ1つを含む。
 */
export const VALUE = (max: number) =>
  String.raw`((?:(?![ \t　][/|｜][ \t　])[^\n\r]){1,${max}})`;
